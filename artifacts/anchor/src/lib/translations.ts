const canonicalOptionSources = new Map<string, string>();
for (const source of [...Object.keys(optNl), ...Object.keys(optEn)]) {
  const id = toStableOptionId(source);
  if (!id) continue;
  const current = canonicalOptionSources.get(id);
  const sourceLooksLikeCopy = /[A-Z\s/]/.test(source);
  const currentLooksLikeCopy = current ? /[A-Z\s/]/.test(current) : false;
  if (!current || (sourceLooksLikeCopy && !currentLooksLikeCopy)) {
    canonicalOptionSources.set(id, source);
  }
}

function readableStableId(value: string): string {
  const words = value.replace(/_/g, "-").split("-").filter(Boolean);
  if (words.length === 0) return value;
  const text = words.join(" ");
  return text.charAt(0).toUpperCase() + text.slice(1);
}

// ─── Public API ───────────────────────────────────────────────

export function getTranslation(lang: Language, key: string): string {
  const dict = lang === "nl" ? nl : en;
  return dict[key] ?? en[key] ?? key;
}

export function getOptionTranslation(lang: Language, str: string): string {
  const direct = lang === "en" ? optEn[str] : optNl[str];
  if (direct) return direct;

  const source = canonicalOptionSources.get(str);
  if (source) {
    return lang === "en"
      ? optEn[source] ?? source
      : optNl[source] ?? optNl[optEn[source] ?? ""] ?? optEn[source] ?? source;
  }

  // Unknown stable IDs remain readable instead of leaking raw storage syntax.
  return /^[a-z0-9]+(?:[-_][a-z0-9]+)+$/.test(str)
    ? readableStableId(str)
    : str;
}
